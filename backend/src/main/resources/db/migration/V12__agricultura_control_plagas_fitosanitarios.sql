CREATE TABLE catalogo_plagas (
    id VARCHAR(36) NOT NULL,
    nombre_comun VARCHAR(160) NOT NULL,
    nombre_cientifico VARCHAR(180) NULL,
    tipo VARCHAR(40) NOT NULL,
    cultivos_afectados VARCHAR(260) NULL,
    descripcion TEXT NULL,
    sintomas TEXT NULL,
    umbral_accion VARCHAR(260) NULL,
    activo BIT NOT NULL DEFAULT b'1',
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    deleted_at DATETIME(6) NULL,
    PRIMARY KEY (id),
    INDEX idx_catalogo_plagas_tipo (tipo),
    INDEX idx_catalogo_plagas_activo (activo),
    INDEX idx_catalogo_plagas_deleted_at (deleted_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE detecciones_plaga (
    id VARCHAR(36) NOT NULL,
    lote_id VARCHAR(36) NOT NULL,
    catalogo_plaga_id VARCHAR(36) NOT NULL,
    fecha_deteccion DATETIME(6) NOT NULL,
    cultivo VARCHAR(80) NULL,
    severidad VARCHAR(40) NOT NULL,
    area_afectada_ha DECIMAL(12,2) NULL,
    porcentaje_afectado DECIMAL(6,2) NULL,
    estado VARCHAR(40) NOT NULL,
    latitud DECIMAL(10,7) NULL,
    longitud DECIMAL(10,7) NULL,
    precision_metros DECIMAL(10,2) NULL,
    origen_geolocalizacion VARCHAR(40) NOT NULL DEFAULT 'MANUAL',
    foto_url VARCHAR(500) NULL,
    foto_nombre VARCHAR(240) NULL,
    foto_content_type VARCHAR(120) NULL,
    foto_tamanio_bytes BIGINT NULL,
    descripcion TEXT NULL,
    responsable VARCHAR(180) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    deleted_at DATETIME(6) NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_deteccion_plaga_lote FOREIGN KEY (lote_id) REFERENCES lotes(id),
    CONSTRAINT fk_deteccion_plaga_catalogo FOREIGN KEY (catalogo_plaga_id) REFERENCES catalogo_plagas(id),
    INDEX idx_deteccion_plaga_lote (lote_id),
    INDEX idx_deteccion_plaga_catalogo (catalogo_plaga_id),
    INDEX idx_deteccion_plaga_estado (estado),
    INDEX idx_deteccion_plaga_severidad (severidad),
    INDEX idx_deteccion_plaga_fecha (fecha_deteccion),
    INDEX idx_deteccion_plaga_deleted_at (deleted_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE aplicaciones_fitosanitarias (
    id VARCHAR(36) NOT NULL,
    deteccion_id VARCHAR(36) NOT NULL,
    lote_id VARCHAR(36) NOT NULL,
    fecha_aplicacion DATETIME(6) NOT NULL,
    producto VARCHAR(180) NOT NULL,
    principio_activo VARCHAR(180) NULL,
    dosis DECIMAL(12,2) NOT NULL,
    unidad_dosis VARCHAR(40) NOT NULL,
    volumen_caldo_l_ha DECIMAL(12,2) NULL,
    superficie_tratada_ha DECIMAL(12,2) NULL,
    periodo_carencia_dias INT NULL,
    periodo_reingreso_horas INT NULL,
    fecha_reingreso_seguro DATETIME(6) NULL,
    fecha_cosecha_segura DATE NULL,
    maquinaria_id VARCHAR(36) NULL,
    operario_responsable VARCHAR(180) NOT NULL,
    condiciones_climaticas VARCHAR(260) NULL,
    observaciones TEXT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    deleted_at DATETIME(6) NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_aplicacion_fito_deteccion FOREIGN KEY (deteccion_id) REFERENCES detecciones_plaga(id),
    CONSTRAINT fk_aplicacion_fito_lote FOREIGN KEY (lote_id) REFERENCES lotes(id),
    INDEX idx_aplicacion_fito_deteccion (deteccion_id),
    INDEX idx_aplicacion_fito_lote (lote_id),
    INDEX idx_aplicacion_fito_fecha (fecha_aplicacion),
    INDEX idx_aplicacion_fito_deleted_at (deleted_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE seguimientos_plaga (
    id VARCHAR(36) NOT NULL,
    deteccion_id VARCHAR(36) NOT NULL,
    fecha DATETIME(6) NOT NULL,
    resultado VARCHAR(40) NOT NULL,
    severidad VARCHAR(40) NOT NULL,
    observaciones TEXT NULL,
    responsable VARCHAR(180) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    deleted_at DATETIME(6) NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_seguimiento_plaga_deteccion FOREIGN KEY (deteccion_id) REFERENCES detecciones_plaga(id),
    INDEX idx_seguimiento_plaga_deteccion (deteccion_id),
    INDEX idx_seguimiento_plaga_fecha (fecha),
    INDEX idx_seguimiento_plaga_deleted_at (deleted_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

