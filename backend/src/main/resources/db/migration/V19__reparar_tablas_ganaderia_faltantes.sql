CREATE TABLE IF NOT EXISTS animales (
    id               VARCHAR(36) NOT NULL DEFAULT (UUID()),
    caravana         VARCHAR(80) NOT NULL,
    raza             VARCHAR(120) NOT NULL,
    sexo             VARCHAR(20) NULL,
    fecha_nacimiento DATE NULL,
    fecha_compra     DATE NULL,
    peso_actual_kg   DECIMAL(10,2) NULL,
    rfid_codigo      VARCHAR(120) NULL,
    qr_codigo        VARCHAR(255) NULL,
    estado           VARCHAR(30) NOT NULL DEFAULT 'ACTIVO',
    ubicacion_actual VARCHAR(150) NULL,
    madre_id         VARCHAR(36) NULL,
    padre_id         VARCHAR(36) NULL,
    observaciones    TEXT NULL,
    created_at       DATETIME(6) DEFAULT CURRENT_TIMESTAMP(6),
    updated_at       DATETIME(6) DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    deleted_at       DATETIME(6) NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_animales_caravana_repair UNIQUE (caravana),
    CONSTRAINT uk_animales_rfid_repair UNIQUE (rfid_codigo),
    CONSTRAINT fk_animales_madre_repair FOREIGN KEY (madre_id) REFERENCES animales(id),
    CONSTRAINT fk_animales_padre_repair FOREIGN KEY (padre_id) REFERENCES animales(id),
    INDEX idx_animales_raza_estado_repair (raza, estado),
    INDEX idx_animales_ubicacion_repair (ubicacion_actual)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS aplicaciones_vacuna (
    id                  VARCHAR(36) NOT NULL DEFAULT (UUID()),
    animal_id           VARCHAR(36) NOT NULL,
    vacuna_id           VARCHAR(36) NOT NULL,
    fecha_aplicacion    DATE NOT NULL,
    proxima_dosis_fecha DATE NULL,
    operario            VARCHAR(120) NULL,
    lote_marca          VARCHAR(120) NULL,
    costo_aplicado      DECIMAL(12,2) NULL,
    observaciones       TEXT NULL,
    created_at          DATETIME(6) DEFAULT CURRENT_TIMESTAMP(6),
    updated_at          DATETIME(6) DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    deleted_at          DATETIME(6) NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_aplicaciones_vacuna_animal_repair FOREIGN KEY (animal_id) REFERENCES animales(id),
    CONSTRAINT fk_aplicaciones_vacuna_catalogo_repair FOREIGN KEY (vacuna_id) REFERENCES vacunas_catalogo(id),
    INDEX idx_aplicaciones_vacuna_fecha_repair (animal_id, fecha_aplicacion),
    INDEX idx_aplicaciones_vacuna_proxima_repair (proxima_dosis_fecha)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS diagnosticos_sanitarios (
    id                   VARCHAR(36) NOT NULL DEFAULT (UUID()),
    animal_id            VARCHAR(36) NOT NULL,
    fecha_diagnostico    DATE NOT NULL,
    enfermedad           VARCHAR(160) NOT NULL,
    severidad            VARCHAR(30) NOT NULL DEFAULT 'MEDIA',
    estado               VARCHAR(30) NOT NULL DEFAULT 'ABIERTO',
    veterinario          VARCHAR(120) NULL,
    tratamiento_indicado VARCHAR(180) NULL,
    observaciones        TEXT NULL,
    created_at           DATETIME(6) DEFAULT CURRENT_TIMESTAMP(6),
    updated_at           DATETIME(6) DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    deleted_at           DATETIME(6) NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_diagnosticos_animal_repair FOREIGN KEY (animal_id) REFERENCES animales(id),
    INDEX idx_diagnosticos_animal_fecha_repair (animal_id, fecha_diagnostico),
    INDEX idx_diagnosticos_estado_repair (estado, severidad)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
