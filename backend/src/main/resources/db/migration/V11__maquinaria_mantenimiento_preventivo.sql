CREATE TABLE planes_mantenimiento (
    id VARCHAR(36) NOT NULL,
    maquinaria_id VARCHAR(36) NULL,
    tipo_maquinaria VARCHAR(80) NULL,
    modelo VARCHAR(120) NULL,
    nombre VARCHAR(160) NOT NULL,
    descripcion TEXT NULL,
    intervalo_horas DECIMAL(12,2) NULL,
    intervalo_dias INT NULL,
    prioridad VARCHAR(40) NOT NULL DEFAULT 'MEDIA',
    activo BIT NOT NULL DEFAULT b'1',
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    deleted_at DATETIME(6) NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_plan_mantenimiento_maquinaria FOREIGN KEY (maquinaria_id) REFERENCES maquinaria(id),
    INDEX idx_plan_mantenimiento_maquinaria (maquinaria_id),
    INDEX idx_plan_mantenimiento_tipo (tipo_maquinaria),
    INDEX idx_plan_mantenimiento_activo (activo),
    INDEX idx_plan_mantenimiento_deleted_at (deleted_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE mantenimientos_programados (
    id VARCHAR(36) NOT NULL,
    maquinaria_id VARCHAR(36) NOT NULL,
    plan_id VARCHAR(36) NULL,
    fecha_programada DATE NOT NULL,
    horometro_objetivo DECIMAL(12,2) NULL,
    estado VARCHAR(40) NOT NULL DEFAULT 'PENDIENTE',
    responsable VARCHAR(180) NULL,
    observaciones TEXT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    deleted_at DATETIME(6) NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_mantenimiento_programado_maquinaria FOREIGN KEY (maquinaria_id) REFERENCES maquinaria(id),
    CONSTRAINT fk_mantenimiento_programado_plan FOREIGN KEY (plan_id) REFERENCES planes_mantenimiento(id),
    INDEX idx_mantenimiento_programado_maquinaria (maquinaria_id),
    INDEX idx_mantenimiento_programado_plan (plan_id),
    INDEX idx_mantenimiento_programado_fecha (fecha_programada),
    INDEX idx_mantenimiento_programado_estado (estado),
    INDEX idx_mantenimiento_programado_deleted_at (deleted_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE intervenciones_mantenimiento (
    id VARCHAR(36) NOT NULL,
    maquinaria_id VARCHAR(36) NOT NULL,
    plan_id VARCHAR(36) NULL,
    programacion_id VARCHAR(36) NULL,
    fecha DATE NOT NULL,
    tipo VARCHAR(60) NOT NULL,
    tareas_realizadas TEXT NOT NULL,
    operario VARCHAR(180) NULL,
    horas_maquina DECIMAL(12,2) NULL,
    mano_obra_costo DECIMAL(14,2) NULL,
    repuestos_costo DECIMAL(14,2) NULL,
    costo_total DECIMAL(14,2) NULL,
    estado_resultante VARCHAR(40) NULL,
    observaciones TEXT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    deleted_at DATETIME(6) NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_intervencion_maquinaria FOREIGN KEY (maquinaria_id) REFERENCES maquinaria(id),
    CONSTRAINT fk_intervencion_plan FOREIGN KEY (plan_id) REFERENCES planes_mantenimiento(id),
    CONSTRAINT fk_intervencion_programacion FOREIGN KEY (programacion_id) REFERENCES mantenimientos_programados(id),
    INDEX idx_intervencion_maquinaria (maquinaria_id),
    INDEX idx_intervencion_fecha (fecha),
    INDEX idx_intervencion_tipo (tipo),
    INDEX idx_intervencion_deleted_at (deleted_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE repuestos_utilizados (
    id VARCHAR(36) NOT NULL,
    intervencion_id VARCHAR(36) NOT NULL,
    codigo VARCHAR(100) NULL,
    descripcion VARCHAR(220) NOT NULL,
    cantidad DECIMAL(12,2) NOT NULL,
    costo_unitario DECIMAL(14,2) NULL,
    costo_total DECIMAL(14,2) NULL,
    proveedor VARCHAR(180) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    deleted_at DATETIME(6) NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_repuesto_intervencion FOREIGN KEY (intervencion_id) REFERENCES intervenciones_mantenimiento(id),
    INDEX idx_repuesto_intervencion (intervencion_id),
    INDEX idx_repuesto_deleted_at (deleted_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
